/** Защита от подбора пароля в базе: слишком много запросов подряд. */
export const TOO_FAST = 'Слишком много попыток подряд — подождите несколько секунд и попробуйте ещё раз.';

/** Понятный текст ошибки запроса к базе — на экран, а не только в консоль. */
export function failText(err, what) {
  console.error(err);
  if (err?.status === 429) return TOO_FAST;
  return err?.status === 0
    ? 'Нет связи с сервером. Проверьте интернет и попробуйте ещё раз.'
    : `Не получилось ${what}. Попробуйте ещё раз; если повторится — напишите Андрею.`;
}
