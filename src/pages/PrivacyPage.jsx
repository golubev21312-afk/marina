import BackHome from '../components/BackHome';
import SiteMenu from '../scenario/SiteMenu';
import { OPERATOR } from '../data/operator';
import { consent, resetConsent, YM_ID } from '../lib/track';
import './AboutPage.css';
import './PrivacyPage.css';

/** Значение реквизита; пропуск в [скобках] подсвечен — его надо заполнить в data/operator.js. */
function F({ value }) {
  return value.startsWith('[') ? <mark className="privacy__todo">{value}</mark> : value;
}

/**
 * Политика обработки персональных данных (152-ФЗ, ст. 18.1): что сайт
 * собирает, зачем, сколько хранит, кому передаёт и как от этого отказаться.
 * Разделы о Яндекс.Метрике показываются, только когда она подключена (VITE_YM_ID).
 */
export default function PrivacyPage() {
  const metrika = Boolean(YM_ID);
  const answer = metrika ? consent() : null;
  let n = 0;
  const h = (title) => (
    <h2>
      {++n}. {title}
    </h2>
  );

  return (
    <div className="page">
      <SiteMenu />
      <div className="page__body appear">
        <article className="wrap privacy">
          <h1>Политика обработки персональных данных</h1>
          <p className="privacy__edition">Редакция от {OPERATOR.edition}</p>

          {h('Общие положения')}
          <p>
            Эта политика объясняет, какие сведения о посетителях собирает сайт мастерской «Крафт»{' '}
            (<F value={OPERATOR.site} />, далее — сайт), зачем и как они обрабатываются. Политика составлена
            по Федеральному закону от 27.07.2006 № 152-ФЗ «О персональных данных».
          </p>
          <p>
            Оператор — <F value={OPERATOR.name} />, <F value={OPERATOR.status} />, ИНН <F value={OPERATOR.inn} />
            {OPERATOR.ogrnip && (
              <>
                , ОГРНИП <F value={OPERATOR.ogrnip} />
              </>
            )}
            . Почта для обращений по персональным данным — <F value={OPERATOR.email} />.
          </p>
          <p>
            Сайт — витрина: на нём нет регистрации, корзины, оплаты и форм. Мы не просим имя, телефон или почту.
            Заказы обсуждаются в сообщениях сообщества «Крафт» ВКонтакте — там действуют правила ВКонтакте.
          </p>

          {h('Какие сведения собираются')}
          <h3>Статистика посещений сайта</h3>
          <p>Чтобы понимать, какие изделия и разделы интересны посетителям, сайт отмечает:</p>
          <ul>
            <li>какие страницы, разделы каталога и изделия открывали;</li>
            <li>нажимали ли кнопку перехода во ВКонтакте;</li>
            <li>с какого сайта пришли — только его адрес, например vk.com или yandex.ru;</li>
            <li>с телефона или с компьютера;</li>
            <li>дату и время;</li>
            <li>
              случайный номер, который браузер хранит у себя (в локальном хранилище, не в cookie), — чтобы два
              захода одного человека не считались как два человека.
            </li>
          </ul>
          <p>
            Имени, телефона, почты и IP-адреса в статистике нет — по ней нельзя узнать, кто именно заходил.
          </p>

          <h3>Технические журналы сервера</h3>
          <p>
            Сервер сайта, как и любой сервер, записывает обращения к нему: IP-адрес, время, запрошенный адрес
            страницы и сведения о браузере. Журналы нужны, чтобы защищать сайт от атак и находить ошибки.
          </p>

          {metrika && (
            <>
              <h3>Яндекс.Метрика — только с вашего согласия</h3>
              <p>
                Если вы нажали «Согласен» в сообщении о cookie, на сайте работает сервис Яндекс.Метрика. Он
                использует cookie и собирает: IP-адрес, сведения о браузере и устройстве, адреса открытых страниц,
                откуда вы пришли, действия на страницах — прокрутку, нажатия, движения мыши (запись посещения,
                «вебвизор»). Если вы нажали «Отказаться», Метрика не загружается и ничего не собирает.
              </p>
            </>
          )}

          {h('Зачем')}
          <ul>
            <li>понимать, чем интересуются посетители, и делать сайт удобнее;</li>
            <li>защищать сайт от атак, подбора паролей и спама.</li>
          </ul>
          <p>Сведения не используются для рекламы и не продаются.</p>

          {h('Основания')}
          <ul>
            {metrika && (
              <li>
                Яндекс.Метрика и cookie — ваше согласие (п. 1 ч. 1 ст. 6 152-ФЗ), которое вы даёте кнопкой
                «Согласен» и можете отозвать в любой момент (раздел 7).
              </li>
            )}
            <li>
              Статистика посещений и журналы сервера — законный интерес оператора: работа и защита сайта (п. 7 ч. 1
              ст. 6 152-ФЗ). Ваши права при этом не нарушаются: сведения не позволяют узнать вашу личность.
            </li>
          </ul>

          {h('Сколько хранятся')}
          <ul>
            <li>статистика посещений — 1 год, затем удаляется автоматически;</li>
            <li>журналы сервера — 5 дней, затем удаляются автоматически;</li>
            {metrika && (
              <li>
                данные Яндекс.Метрики — по правилам Яндекса; cookie Метрики хранятся в вашем браузере до 1 года, их
                можно удалить в настройках браузера.
              </li>
            )}
          </ul>

          {h('Кому передаются')}
          <ul>
            <li>
              Сайт и база работают на серверах <F value={OPERATOR.hosting} /> в России. Сведения хранятся в России,
              за границу не передаются.
            </li>
            {metrika && (
              <li>
                Если вы согласились на Метрику — ООО «ЯНДЕКС» (ИНН 7736207543, 119021, г. Москва, ул. Льва Толстого,
                д. 16), которое обрабатывает данные по своей политике конфиденциальности (yandex.ru/legal/confidential).
              </li>
            )}
            <li>Больше никому — кроме случаев, когда этого прямо требует закон.</li>
          </ul>

          {h('Как отказаться')}
          {metrika ? (
            <>
              <p>
                Отозвать согласие на Яндекс.Метрику можно в любой момент: кнопкой ниже, удалив cookie в настройках
                браузера или написав на <F value={OPERATOR.email} />.
              </p>
              <p className="privacy__consent">
                Сейчас: {answer === 'yes' ? 'вы согласились на Яндекс.Метрику' : answer === 'no' ? 'вы отказались от Яндекс.Метрики' : 'вы ещё не отвечали'}.
                <button type="button" onClick={resetConsent}>
                  Изменить решение о cookie
                </button>
              </p>
            </>
          ) : (
            <p>
              Cookie на сайте не используются. Удалить случайный номер для статистики можно, очистив данные сайта
              в настройках браузера.
            </p>
          )}

          {h('Ваши права')}
          <p>Вы можете:</p>
          <ul>
            <li>узнать, обрабатываются ли ваши данные, какие и зачем;</li>
            <li>потребовать уточнить, заблокировать или удалить их;</li>
            <li>отозвать согласие;</li>
            <li>
              пожаловаться в Роскомнадзор (rkn.gov.ru) или в суд, если считаете, что ваши права нарушены.
            </li>
          </ul>
          <p>
            Напишите на <F value={OPERATOR.email} /> — ответим в течение 10 рабочих дней. Чтобы найти ваши записи
            в статистике, может понадобиться случайный номер из вашего браузера — подскажем, как его посмотреть.
          </p>

          {h('Как сведения защищены')}
          <p>
            Сайт открывается по защищённому соединению (HTTPS). Статистику видят только мастер и администратор
            сайта — по личному паролю. Изменить или удалить записи через сайт нельзя.
          </p>

          {h('Изменения политики')}
          <p>
            Политику можно обновить — например, если сайт начнёт собирать что-то ещё. Новая редакция действует
            с момента публикации на этой странице; дата редакции указана вверху.
          </p>
        </article>
      </div>
      <BackHome />
    </div>
  );
}
